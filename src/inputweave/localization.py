def language_name(code: str) -> str:
    return LANGUAGES.get(code, LANGUAGES["de"])


def language_code(name: str) -> str:
    return next((code for code, label in LANGUAGES.items() if label == name), "de")


def translate(text: str, language: str) -> str:
    """Translate a German source string; unknown strings safely stay readable."""
    return TRANSLATIONS.get(language, {}).get(text, text)


def translate_format(template: str, language: str, **values: str) -> str:
    """Translate and format a user-facing message template."""
    return translate(template, language).format(**values)


def canonical_text(text: str) -> str:
    """Find the German catalog key for a string already translated in any UI language."""
    for translations in TRANSLATIONS.values():
        for source, localized in translations.items():
            if text == localized:
                return source
    return text


